// The kernel's build script, run on the host before the kernel compiles:
// - links the kernel with our linker script (addresses and sections Limine
//   expects);
// - turns the console font into ready-made letter images, so the kernel
//   only copies pixels and never has to read a font file itself.

use std::fmt::Write as _;
use std::{env, fs, path::PathBuf};

/// The console font (SIL Open Font License, see fonts/FiraCode-LICENSE.txt).
const FONT: &str = "fonts/FiraCode-Regular.ttf";
/// Text row heights the kernel can choose from, in pixels, smallest first.
const ROW_HEIGHTS: [usize; 3] = [16, 24, 32];

fn main() {
    let dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    println!("cargo:rustc-link-arg=-T{dir}/linker.ld");
    println!("cargo:rerun-if-changed=linker.ld");
    println!("cargo:rerun-if-changed={FONT}");

    let font = fontdue::Font::from_bytes(fs::read(format!("{dir}/{FONT}")).unwrap(), fontdue::FontSettings::default())
        .unwrap_or_else(|e| panic!("{FONT}: {e}"));
    let out = PathBuf::from(env::var("OUT_DIR").unwrap());
    let mut rust = format!("// Generated by build.rs from {FONT}.\n\nstatic FONTS: [Font; {}] = [\n", ROW_HEIGHTS.len());

    for height in ROW_HEIGHTS {
        // The font size at which one line (ascent above the baseline plus
        // descent below it) exactly fills the row.
        let unit = font.horizontal_line_metrics(1.0).unwrap();
        let px = height as f32 / (unit.ascent - unit.descent);
        let baseline = font.horizontal_line_metrics(px).unwrap().ascent.round() as i32;
        // Monospace: every character advances the pen by the same amount.
        let width = font.metrics('M', px).advance_width.round() as usize;

        // One width x height cell per printable ASCII character, ' ' to '~',
        // one brightness byte (0-255) per pixel.
        let mut cells = Vec::new();
        for c in ' '..='~' {
            let (m, bitmap) = font.rasterize(c, px);
            let mut cell = vec![0u8; width * height];
            // The glyph image's bottom-left corner sits `xmin` right of the
            // pen and `ymin` above the baseline.
            let top = baseline - m.ymin - m.height as i32;
            for y in 0..m.height {
                for x in 0..m.width {
                    let (cx, cy) = (m.xmin + x as i32, top + y as i32);
                    if (0..width as i32).contains(&cx) && (0..height as i32).contains(&cy) {
                        cell[cy as usize * width + cx as usize] = bitmap[y * m.width + x];
                    }
                }
            }
            cells.extend(cell);
        }
        let file = format!("font-{height}.bin");
        fs::write(out.join(&file), cells).unwrap();
        writeln!(rust, "    Font {{ width: {width}, height: {height}, cells: include_bytes!(concat!(env!(\"OUT_DIR\"), \"/{file}\")) }},").unwrap();
    }
    rust.push_str("];\n");
    fs::write(out.join("fonts.rs"), rust).unwrap();
}
